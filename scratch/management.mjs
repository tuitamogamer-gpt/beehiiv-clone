import {chromium,expect} from '@playwright/test';
import {mkdirSync} from 'node:fs';
mkdirSync('artifacts', {recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const go=async label=>{await page.locator('.sidebar').getByRole('button',{name:label,exact:true}).click();await page.locator('.page-loading').waitFor({state:'hidden'})};
try{
await page.goto(process.env.BASE_URL || 'http://localhost:5173');await page.getByRole('heading',{name:'Welcome back, Alex'}).waitFor();
await page.keyboard.press('Control+k');
await page.getByPlaceholder('Search posts, subscribers, or your workspace...').fill('Olivia');
await page.locator('.search-result').click();
await expect(page.getByRole('dialog',{name:'Subscriber details'})).toContainText('Olivia Rhye');
await page.keyboard.press('Escape');
await expect(page.getByRole('dialog')).toHaveCount(0);
console.log('PASS command search opens matching subscriber and Escape dismisses');
await page.getByRole('button',{name:'Segments',exact:true}).click();
await page.getByRole('button',{name:'Create segment',exact:true}).click();
await page.getByLabel('Segment name',{exact:true}).fill('Premium insiders');
await page.getByRole('dialog').getByLabel(/^Subscription/).selectOption('Premium');
await page.getByRole('button',{name:'Save segment',exact:true}).click();
await expect(page.locator('.aud-segment').filter({hasText:'Premium insiders'})).toContainText('4 subscribers');
await page.reload();await page.getByRole('button',{name:'Segments',exact:true}).click();
await expect(page.locator('.aud-segment')).toContainText('Premium insiders');
console.log('PASS dynamic segment save and reload');
await go('Settings');
await page.getByRole('button',{name:'Team',exact:true}).click();
await page.getByRole('button',{name:'Invite teammate',exact:true}).click();
await page.getByLabel('Full name',{exact:true}).fill('Taylor Smith');
await page.getByLabel('Email address',{exact:true}).fill('taylor@example.com');
await page.getByLabel(/^Publication role/).selectOption('Contributor');
await page.getByRole('button',{name:'Save invitation',exact:true}).click();
await expect(page.locator('.settings-team')).toContainText('Taylor Smith');
await expect(page.getByRole('combobox',{name:'Role for Taylor Smith'})).toHaveValue('Contributor');
await page.getByRole('combobox',{name:'Role for Taylor Smith'}).selectOption('Member');
await page.getByRole('button',{name:'Remove Taylor Smith',exact:true}).click();
await expect(page.locator('.settings-team')).not.toContainText('Taylor Smith');
console.log('PASS local team invitation, role changes, access removal');
await page.getByRole('button',{name:'Deliverability',exact:true}).click();
await page.getByRole('button',{name:'Add suppression',exact:true}).click();
await page.getByLabel('Email address',{exact:true}).fill('suppressed@example.com');
await page.getByLabel(/^Scope/).selectOption('Transactional');
await page.getByLabel(/^Duration/).selectOption('7');
await page.getByRole('dialog').getByRole('button',{name:'Add suppression',exact:true}).click();
await expect(page.locator('.settings-suppression')).toContainText('suppressed@example.com');
await expect(page.locator('.settings-suppression')).toContainText('Transactional');
await page.getByRole('button',{name:'Remove suppression for suppressed@example.com'}).click();
await expect(page.locator('.settings-suppression')).not.toContainText('suppressed@example.com');
console.log('PASS scoped temporary suppression add/remove');
await go('Home');
await page.getByRole('button',{name:'Getting started 3'}).click();
await expect(page.locator('.onboarding')).toBeVisible();
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.getByRole('button',{name:'Last 30 days',exact:true}).click();
await page.getByRole('button',{name:'Last 7 days',exact:true}).click();
await expect(page.locator('.metric-card').last()).toContainText('$1,216.00');
await page.getByRole('button',{name:'Engagement',exact:true}).click();
await expect(page.locator('.growth-chart')).toContainText('75%');
await page.getByRole('button',{name:'Compare to previous period'}).click();
await expect(page.locator('.chart-legend')).not.toContainText('Previous period');
console.log('PASS overview onboarding, date period, chart tabs, comparison toggle');
console.log('ALL MANAGEMENT TESTS PASSED; errors:',errors);
}catch(e){console.log('FAIL',e.message);await page.screenshot({path:'artifacts/management-failure.png',fullPage:true});process.exitCode=1}finally{await browser.close()}
